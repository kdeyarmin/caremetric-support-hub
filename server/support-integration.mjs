// Actual PostgreSQL authorization on disposable local fixtures only.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { digest } from './sms-auth.mjs';
import { gateway } from './gateway.mjs';
const databaseUrl=process.env.HUB_TEST_DATABASE_URL;
const local=new URL(databaseUrl);assert.equal(local.hostname,'127.0.0.1');assert.equal(local.port,'54322');
const admin=new pg.Pool({connectionString:databaseUrl});
await admin.query("alter role hub_app_server login password 'ephemeral-test-only'");
const appUrl=new URL(databaseUrl);appUrl.username='hub_app_server';appUrl.password='ephemeral-test-only';
const pool=new pg.Pool({connectionString:appUrl.href});const api=gateway(pool);
const owner=randomUUID(),customer=randomUUID(),tenant=randomUUID(),otherTenant=randomUUID();
const ownerToken='support-owner-'+randomUUID(),customerToken='support-customer-'+randomUUID();
const ownerSession=randomUUID(),customerSession=randomUUID();
const product=(await admin.query("select id from hub.products where slug='caremetric-go'")).rows[0].id;
const otherProduct=(await admin.query("select id from hub.products where slug='breathe'")).rows[0].id;
const rpc=(name,args={},token=ownerToken)=>api.rpc(name,args,token);
const page=()=>rpc('list_support_intake_tenants',{p_product_id:product,p_offset:0,p_limit:50});
const current=async()=>(await page()).rows.find(row=>row.tenantId===tenant);
const set=async(enabled,extra={})=>rpc('set_support_intake',{p_tenant_id:tenant,p_product_id:product,p_enabled:enabled,p_reviewed:true,p_expected_updated_at:(await current()).updatedAt,...extra});
try {
  await admin.query(`insert into auth.users(id,email,is_anonymous) values($1,'support-owner@test.invalid',false),($2,'support-customer@test.invalid',false)`,[owner,customer]);
  await admin.query("insert into private.staff_permissions(user_id,permission) values($1,'platform.admin')",[owner]);
  await admin.query("insert into private.sms_identities(user_id,phone_e164,verified_at) values($1,'+12025550401',now()),($2,'+12025550402',now())",[owner,customer]);
  for(const [id,user,token] of [[ownerSession,owner,ownerToken],[customerSession,customer,customerToken]]) {
    await admin.query("insert into private.sms_sessions(id,token_hash,user_id,identity_version,expires_at) select $1,$2,user_id,identity_version,now()+interval '1 hour' from private.sms_identities where user_id=$3",[id,digest(token),user]);
  }
  await admin.query("insert into hub.tenants(id,slug,name) values($1,$2,'Support integration customer'),($3,$4,'Support integration other')",[tenant,'support-'+tenant,otherTenant,'support-'+otherTenant]);
  await admin.query('insert into hub.tenant_products(tenant_id,product_id) values($1,$2),($3,$2)',[tenant,product,otherTenant]);
  await assert.rejects(rpc('get_support_readiness',{},null));
  await assert.rejects(rpc('get_support_readiness',{},customerToken));
  await assert.rejects(set(true),/verified SMS customer/,'empty access cannot activate intake');
  await admin.query('insert into hub.tenant_product_memberships(tenant_id,product_id,user_id) values($1,$2,$3)',[tenant,product,customer]);
  await assert.rejects(set(true,{p_reviewed:false}),/Review/);
  await assert.rejects(set(true,{p_product_id:otherProduct}),/Existing customer access/,'no implicit cross-product entitlement');
  await assert.rejects(set(true,{p_expected_updated_at:new Date().toISOString()}),/changed/);
  assert.equal((await current()).usableMemberCount,1);
  const before=(await rpc('get_support_readiness')).products.find(p=>p.id===product);
  assert.equal(before.readyTenantCount,0);
  await set(true);assert.equal((await current()).ready,true);
  assert.equal((await rpc('get_support_readiness')).products.find(p=>p.id===product).readyTenantCount,1);
  await assert.rejects(set(false,{p_expected_updated_at:null}),/changed/,'old read cannot overwrite current settings');
  const caseArgs={p_tenant_id:tenant,p_product_id:product,p_subject:'Synthetic intake integration',p_category:'general',p_priority:'normal',p_body:'Synthetic nonclinical support fixture',p_app_version:null,p_route:null,p_contains_phi:false,p_request_key:randomUUID()};
  await rpc('create_support_case',caseArgs,customerToken);
  await admin.query("update hub.tenant_product_memberships set status='suspended',revoked_at=now() where tenant_id=$1",[tenant]);
  assert.equal((await current()).ready,false);assert.equal((await current()).usableMemberCount,0);
  await assert.rejects(set(true),/verified SMS customer/);
  await assert.rejects(rpc('create_support_case',{...caseArgs,p_request_key:randomUUID()},customerToken));
  await set(false);assert.equal((await current()).enabled,false,'disable remains available when access is revoked');
  await admin.query("update hub.tenant_product_memberships set status='active',revoked_at=null where tenant_id=$1",[tenant]);
  await admin.query('update private.sms_identities set revoked_at=now() where user_id=$1',[customer]);
  await assert.rejects(set(true),/verified SMS customer/);
  await admin.query('update private.sms_identities set revoked_at=null where user_id=$1',[customer]);
  await admin.query("update auth.users set banned_until=now()+interval '1 hour' where id=$1",[customer]);
  assert.equal((await current()).usableMemberCount,0);await assert.rejects(set(true),/verified SMS customer/);
  await admin.query('update auth.users set banned_until=null where id=$1',[customer]);
  await admin.query("update hub.tenant_products set status='suspended' where tenant_id=$1",[tenant]);
  await assert.rejects(set(true),/Active access/);
  await admin.query("update hub.tenant_products set status='active' where tenant_id=$1",[tenant]);
  await admin.query("update private.sms_sessions set created_at=now()-interval '9 hours' where id=$1",[ownerSession]);
  await assert.rejects(set(true),/Current administrator session/);
  await admin.query('update private.sms_sessions set created_at=now() where id=$1',[ownerSession]);
  await admin.query('update private.staff_permissions set revoked_at=now() where user_id=$1',[owner]);
  await assert.rejects(rpc('get_support_readiness'));await assert.rejects(set(true));
  await admin.query('update private.staff_permissions set revoked_at=null where user_id=$1',[owner]);
  await assert.rejects(rpc('list_support_intake_tenants',{p_product_id:product,p_offset:-1}),/Invalid page/);
  const first=await rpc('list_support_intake_tenants',{p_product_id:product,p_offset:0,p_limit:1});
  const second=await rpc('list_support_intake_tenants',{p_product_id:product,p_offset:1,p_limit:1});
  assert.equal(first.rows.length,1);assert.equal(second.rows.length,1);assert.notEqual(first.rows[0].tenantId,second.rows[0].tenantId);
  const audit=(await admin.query("select metadata from private.audit_events where actor_id=$1 and action='support.intake.set' order by id",[owner])).rows;
  assert.deepEqual(audit.map(row=>row.metadata.enabled),[true,false]);
  assert.ok(audit.every(row=>Object.keys(row.metadata).sort().join(',')==='enabled,previousEnabled,reviewed'));
  console.log('Support readiness: actual SMS-authorized reads, reviewed intake, case creation, revocation, stale changes, pagination and audit passed.');
} finally {
  await admin.query('delete from hub.support_cases where tenant_id in ($1,$2)',[tenant,otherTenant]);
  await admin.query('delete from private.audit_events where actor_id in ($1,$2)',[owner,customer]);
  await admin.query('delete from hub.tenants where id in ($1,$2)',[tenant,otherTenant]);
  await admin.query('delete from private.sms_sessions where user_id in ($1,$2)',[owner,customer]);
  await admin.query('delete from private.sms_identities where user_id in ($1,$2)',[owner,customer]);
  await admin.query('delete from auth.users where id in ($1,$2)',[owner,customer]);
  await pool.end();await admin.end();
}
