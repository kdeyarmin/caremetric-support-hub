import { createHash } from 'node:crypto';

/**
 * The migration that publishes docs/self-service/guides.json (npm run generate:guides).
 *
 * A migration that has run is never run again, so a change to the guides is published by a new migration, never by rewriting one
 * that production already applied. Each generated migration states every guide in full and brings the database to it, whatever it
 * found: a guide gets a new revision only when its text changed (revisions are kept, never edited), is published at the revision
 * holding its current text in exactly the applications it names, and a guide the file no longer has is unpublished. Running one twice,
 * or an older one before a newer one, ends in the state the newest states.
 */
export const generatedMarker = '-- Generated by npm run generate:guides from docs/self-service/guides.json.';

const literal = value => `'${String(value).replaceAll("'", "''")}'`;
const textArray = values => `array[${values.map(literal).join(',')}]::text[]`;
const sections = { prerequisites: 'Prerequisites', roles: 'Permitted roles', setup: 'Setup', use: 'Normal use', problems: 'Common problems', faq: 'FAQ', tips: 'Helpful tips' };

/** The guide's article, exactly as the first generated migration wrote it, so an unchanged guide keeps its revision. */
export function guideBody(guide) {
  return Object.entries(sections).map(([field, heading]) => `## ${heading}\n\n${guide[field].map((value, index) => `${field === 'setup' || field === 'use' ? `${index + 1}.` : '-'} ${value}`).join('\n')}`).join('\n\n');
}

function guideBlock(guide) {
  const key = `self-service.${guide.id}`;
  const body = guideBody(guide);
  const variables = JSON.stringify({ features: guide.features });
  const hash = createHash('sha256').update(JSON.stringify([guide.title, guide.summary, body, variables])).digest('hex');
  return `-- ${key}
do $guide$
declare
  v_key constant text := ${literal(key)};
  v_item constant uuid := md5(${literal(key)})::uuid;
  v_title constant text := ${literal(guide.title)};
  v_summary constant text := ${literal(guide.summary)};
  v_body constant text := ${literal(body)};
  v_variables constant jsonb := ${literal(variables)}::jsonb;
  v_apps constant text[] := ${textArray(guide.apps)};
  v_revision uuid;
  v_next integer;
begin
  insert into hub.content_items(id,content_key,kind,status,access_level,source_system,owner_team)
  values(v_item,v_key,'article','published','customer','support_hub','CareMetric Support') on conflict(id) do nothing;
  select r.id into v_revision from hub.content_revisions r
   where r.item_id=v_item and r.locale='en-US' and r.product_overlay_id is null
     and r.title=v_title and r.summary=v_summary and r.body_markdown=v_body and r.variables=v_variables
   order by r.revision_no desc limit 1;
  if v_revision is null then
    select coalesce(max(r.revision_no),0)+1 into v_next from hub.content_revisions r
     where r.item_id=v_item and r.locale='en-US' and r.product_overlay_id is null;
    insert into hub.content_revisions(id,item_id,revision_no,locale,title,summary,body_markdown,body_text,variables,source_hash,source_version,review_state,approved_at)
    values(md5(v_key||':revision:'||v_next)::uuid,v_item,v_next,'en-US',v_title,v_summary,v_body,v_body,v_variables,${literal(hash)},'guides.json','approved',now())
    returning id into v_revision;
  end if;
  insert into hub.content_publications(id,item_id,revision_id,product_id,audience)
  select md5(v_key||':publication:'||p.slug)::uuid,v_item,v_revision,p.id,array['all']::text[] from hub.products p where p.slug=any(v_apps)
  on conflict(item_id,product_id) do update set revision_id=excluded.revision_id,audience=excluded.audience
   where hub.content_publications.revision_id is distinct from excluded.revision_id or hub.content_publications.audience is distinct from excluded.audience;
  delete from hub.content_publications cp
   where cp.item_id=v_item and not exists(select 1 from hub.products p where p.id=cp.product_id and p.slug=any(v_apps));
end;
$guide$;
`;
}

/** The whole migration for these guides. */
export function guidesMigration(guides) {
  return [`${generatedMarker} Do not edit it: change the guides and run
-- npm run generate:guides again, which writes a new migration (one that has run is never run again).
--
-- Brings every maintained guide to the file: a new revision only when its text changed, published at that revision in exactly the
-- applications it names, and unpublished when the file no longer has it (scripts/self-service-guides.mjs).
set local lock_timeout = '10s';
`, ...guides.map(guideBlock), `-- A guide the file no longer has.
delete from hub.content_publications cp using hub.content_items i
 where cp.item_id=i.id and i.content_key like 'self-service.%' and i.content_key<>all(${textArray(guides.map(guide => `self-service.${guide.id}`))});
`].join('\n');
}

/** The newest generated migration among [{name, text}], or null. */
export function latestGenerated(files) {
  return [...files].sort((a, b) => a.name.localeCompare(b.name)).filter(file => file.text.startsWith(generatedMarker)).at(-1) ?? null;
}

const stamp = date => date.toISOString().replace(/\D/g, '').slice(0, 14);
const parse = value => new Date(`${value.slice(0, 4)}-${value.slice(4, 6)}-${value.slice(6, 8)}T${value.slice(8, 10)}:${value.slice(10, 12)}:${value.slice(12, 14)}Z`);

/** A name that sorts after every migration there is, some of which are dated ahead of today. */
export function nextMigrationName(names, now = new Date()) {
  const newest = names.map(name => /^(\d{14})_/.exec(name)?.[1]).filter(Boolean).sort().at(-1);
  const after = newest ? new Date(parse(newest).getTime() + 60_000) : now;
  return `${stamp(after > now ? after : now)}_self_service_guides.sql`;
}
